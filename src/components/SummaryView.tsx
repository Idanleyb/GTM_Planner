import { useState } from 'react'
import type { Project, SectionId } from '../config/types'
import { NOT_SET, buildSummary, paragraphs } from '../engine/summary'
import type { KV, SummaryBlock, SummaryTable } from '../engine/summary'
import { downloadSummaryDoc } from '../lib/downloadSummary'
import { LinkButton } from './Panels'

/** The plan on one page: the dashboard in the app and the content of the Word download. */
export function SummaryView({ project, today, onNavigate }: { project: Project; today: Date; onNavigate: (id: SectionId) => void }) {
  const s = buildSummary(project, today)
  const [busy, setBusy] = useState(false)
  const [error, setError] = useState<string | null>(null)
  const download = async () => {
    setBusy(true); setError(null)
    try { await downloadSummaryDoc(project, today) } catch (e) { setError(`The Word file couldn’t be created: ${e instanceof Error ? e.message : String(e)}`) } finally { setBusy(false) }
  }

  return (
    <article aria-labelledby="summary-title" className="mx-auto max-w-5xl">
      <header className="mb-8 flex flex-wrap items-end justify-between gap-4">
        <div className="min-w-0">
          <p className="m-0 text-sm font-semibold text-ink-muted">Plan summary</p>
          <h1 id="summary-title" className="m-0 mt-1 text-3xl font-bold tracking-tight text-ink">{s.title}</h1>
          <p className="mb-0 mt-2 text-ink-soft">{s.subtitle}</p>
        </div>
        <div className="flex flex-wrap gap-2 print:hidden">
          <button type="button" onClick={() => void download()} disabled={busy} className="rounded-md bg-ink px-4 py-2.5 font-semibold text-white hover:bg-ink-soft disabled:opacity-60">
            {busy ? 'Creating the document…' : 'Download Word doc'}
          </button>
          <button type="button" onClick={() => window.print()} className="rounded-md border border-line bg-sheet px-4 py-2.5 font-semibold text-ink hover:border-ink-muted">Print or save as PDF</button>
        </div>
      </header>
      {error && <p role="alert" className="mb-6 rounded-md bg-alert-soft px-3 py-2 text-sm text-alert">{error}</p>}

      <Facts items={s.keyFacts} columns={2} />

      <section aria-labelledby="sum-ready" className="mt-10">
        <h2 id="sum-ready" className="m-0 border-b-2 border-signal pb-2 text-xl font-bold text-ink">Where the plan stands</h2>
        <p className="mt-4 text-lg text-ink"><b>{s.readiness.pct}% complete</b>, {s.readiness.ready} of {s.readiness.total} steps ready.</p>
        <DataTable table={s.readiness.phases} />
        {s.gaps.length > 0 && (
          <>
            <h3 className="mb-2 mt-6 text-base font-bold text-ink">Still needed before each step is ready</h3>
            <ul className="m-0 space-y-1.5 pl-5">
              {s.gaps.map(g => (
                <li key={g.sectionId}>
                  <LinkButton onClick={() => onNavigate(g.sectionId)}>{g.step}</LinkButton>: <span className="text-ink-soft">{g.missing.join('; ')}</span>
                </li>
              ))}
            </ul>
          </>
        )}
        {s.dueSoon.rows.length > 0 && (
          <>
            <h3 className="mb-2 mt-6 text-base font-bold text-ink">Due in the next two weeks</h3>
            <DataTable table={s.dueSoon} />
          </>
        )}
      </section>

      {s.sections.map((sec, i) => (
        <section key={sec.id} aria-labelledby={`sum-${sec.id}`} className="mt-10 break-inside-avoid-page">
          <div className="flex items-end justify-between gap-3 border-b-2 border-signal pb-2">
            <h2 id={`sum-${sec.id}`} className="m-0 text-xl font-bold text-ink"><span className="mr-2 text-signal">{i + 1}</span>{sec.title}</h2>
            <span className="print:hidden"><LinkButton onClick={() => onNavigate(sec.editSection)}>Edit</LinkButton></span>
          </div>
          <div className="mt-4 space-y-5">{sec.blocks.map((b, j) => <Block key={j} b={b} />)}</div>
        </section>
      ))}

      <p className="mt-12 border-t border-line pt-3 text-sm text-ink-muted">Generated by GTM Planner on {s.generatedOn}.</p>
    </article>
  )
}

function Block({ b }: { b: SummaryBlock }) {
  switch (b.kind) {
    case 'facts': return <Facts items={b.items} />
    case 'text': return (
      <div className="max-w-[72ch]">
        <h3 className="m-0 text-sm font-bold text-ink">{b.label}</h3>
        {paragraphs(b.text).map((t, i) => <p key={i} className="mb-0 mt-1 text-ink-soft">{t}</p>)}
      </div>
    )
    case 'table': return <div>{b.title && <h3 className="m-0 mb-2 text-base font-bold text-ink">{b.title}</h3>}<DataTable table={b.table} /></div>
    case 'bullets': return (
      <div>
        {b.title && <h3 className="m-0 mb-1 text-base font-bold text-ink">{b.title}</h3>}
        <ul className="m-0 space-y-1 pl-5 text-ink-soft">{b.items.map((t, i) => <li key={i}>{t}</li>)}</ul>
      </div>
    )
    case 'empty': return <p className="m-0 italic text-ink-muted">{b.text}</p>
  }
}

function Facts({ items, columns = 1 }: { items: KV[]; columns?: 1 | 2 }) {
  return (
    <dl className={`m-0 grid overflow-hidden rounded-lg border border-line bg-sheet ${columns === 2 ? 'sm:grid-cols-2' : ''}`}>
      {items.map(kv => (
        <div key={kv.label} className="grid grid-cols-[minmax(8rem,2fr)_3fr] border-b border-line last:border-b-0 sm:[&:nth-last-child(2)]:border-b-0">
          <dt className="bg-paper px-3 py-2 text-sm font-semibold text-ink">{kv.label}</dt>
          <dd className={`m-0 px-3 py-2 text-sm ${kv.value === NOT_SET ? 'italic text-ink-muted' : 'text-ink-soft'}`}>{kv.value}</dd>
        </div>
      ))}
    </dl>
  )
}

function DataTable({ table }: { table: SummaryTable }) {
  const total = table.widths.reduce((a, b) => a + b, 0)
  return (
    <div className="overflow-x-auto rounded-lg border border-line">
      <table className="w-full min-w-[36rem] border-collapse bg-sheet text-sm">
        <colgroup>{table.widths.map((w, i) => <col key={i} style={{ width: `${(w / total) * 100}%` }} />)}</colgroup>
        <thead><tr className="bg-ink text-left text-white">{table.columns.map(c => <th key={c} scope="col" className="px-3 py-2 font-semibold">{c}</th>)}</tr></thead>
        <tbody>
          {table.rows.map((r, i) => (
            <tr key={i} className={`align-top ${i % 2 ? 'bg-paper' : ''}`}>
              {r.map((v, j) => <td key={j} className={`border-t border-line px-3 py-2 ${j === 0 ? 'font-semibold text-ink' : 'text-ink-soft'}`}>{paragraphs(v).map((t, k) => <span key={k} className="block">{t}</span>)}</td>)}
            </tr>
          ))}
        </tbody>
      </table>
    </div>
  )
}
